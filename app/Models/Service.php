<?php

namespace App\Models;

use App\Concerns\CachesContent;
use App\Concerns\HasComments;
use App\Concerns\HasCreator;
use App\Concerns\HasReviews;
use App\Concerns\HasSlug;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\HasOne;
use Illuminate\Support\Str;
use Illuminate\Database\Eloquent\SoftDeletes;
use Spatie\Translatable\HasTranslations;

class Service extends Model
{
    use CachesContent, HasComments, HasCreator, HasFactory, HasReviews, HasSlug, HasTranslations, SoftDeletes;

    public array $translatable = ['name', 'description'];

    protected $fillable = [
        'name', 'description', 'slug', 'price', 'featured_image', 'status', 'sort_order', 'created_by',
    ];

    protected function casts(): array
    {
        return [
            'price' => 'decimal:2',
            'sort_order' => 'integer',
        ];
    }

    protected static function booted(): void
    {
        // Every service owns a paired Page (type 'service'): created with the
        // service, kept in step with its name/description/status afterwards.
        // The page's slug is generated by HasSlug (the service already holds
        // its own, so the page's gets a -2 suffix) and is never overwritten.
        static::saved(function (Service $service) {
            $page = Page::firstOrNew(['type' => 'service', 'service_id' => $service->id]);

            $page->fill([
                'user_id' => $page->user_id ?: ($service->created_by ?: auth()->id()),
                'title' => $service->getTranslations('name'),
                'description' => $service->getTranslations('description') ?: null,
                'status' => $service->status === 'active' ? 'active' : 'inactive',
            ]);

            // The page's SEO row is created with the page (HasSeo). Seed it from
            // the service's own copy, but only fields still blank — SEO an admin
            // wrote by hand on the page is never overwritten by a service edit.
            foreach ($service->seoDefaults() as $field => $value) {
                $blank = in_array($field, Seo::TRANSLATABLE, true)
                    ? array_filter($page->ownSeoTranslations($field), 'filled') === []
                    : blank($page->ownSeoAttribute($field));

                if ($blank && filled($value)) {
                    $page->{$field} = $value;
                }
            }

            if ($page->user_id) {
                $page->save();
            }
        });

        // Same as products/posts: the page goes with the service (a restore
        // re-saves the service, which brings the page back via the hook above).
        static::deleted(fn (Service $service) => $service->page()->delete());
    }

    /**
     * What the paired page's SEO starts from: title and plain-text description
     * per locale (so bn stays bn), and the featured image for the social cards.
     *
     * @return array<string, mixed>
     */
    protected function seoDefaults(): array
    {
        $titles = array_filter($this->getTranslations('name'), 'filled');
        $descriptions = [];

        foreach (array_filter($this->getTranslations('description'), 'filled') as $locale => $html) {
            $descriptions[$locale] = Str::limit(trim(preg_replace('/\s+/', ' ', strip_tags(html_entity_decode((string) $html)))), 160, '');
        }

        $descriptions = array_filter($descriptions, 'filled');

        return [
            'seo_title' => $titles,
            'og_title' => $titles,
            'twitter_title' => $titles,
            'seo_description' => $descriptions,
            'og_description' => $descriptions,
            'twitter_description' => $descriptions,
            'og_image' => $this->featured_image,
            'twitter_image' => $this->featured_image,
        ];
    }

    public function page(): HasOne
    {
        return $this->hasOne(Page::class, 'service_id')->where('type', 'service');
    }

    public function scopeActive(Builder $query): Builder
    {
        return $query->where('status', 'active');
    }
}
